-- Generated mission content, applied on top of the Mission Editor source.
--
--   generate.apply(mission, warehouses)  -- edits both tables in place
--
-- Generated groups are recognised by name prefix and replaced on every run, so
-- applying to an already-built mission gives the same result. Lua 5.1.

local helicopters = require("helicopters")
local aircraftTypes = require("aircraft_types")
local layout = require("layout")

local M = {}

-- Players pick slots by group name (both slot lists show and sort by it), so groups
-- are named for players: "UH-1H Cold Start". Unit names carry this prefix, which is
-- how the build (and later, mission scripts) recognise generated slots.
M.SLOT_PREFIX = "RG Slot "
local BLUE_COUNTRY = { id = 80, name = "Combined Joint Task Forces Blue" }

local START = {
  cold = { label = "Cold Start", type = "TakeOffParking", action = "From Parking Area" },
  hot  = { label = "Hot Start",  type = "TakeOffParkingHot", action = "From Parking Area Hot" },
}

-- Walk every group in the mission, last first, calling fn(groupList, index, group).
local function eachGroup(mission, fn)
  for _, side in pairs(mission.coalition) do
    for _, country in ipairs(side.country or {}) do
      for _, category in ipairs({ "plane", "helicopter", "vehicle", "ship", "static" }) do
        local cat = country[category]
        if cat and cat.group then
          for i = #cat.group, 1, -1 do fn(cat.group, i, cat.group[i]) end
        end
      end
    end
  end
end

local function hasPrefix(name)
  return type(name) == "string" and name:sub(1, #M.SLOT_PREFIX) == M.SLOT_PREFIX
end

-- Generated by the unit-name prefix; the group-name check also catches slots from
-- builds before groups got player-facing names.
local function isGenerated(group)
  local unit = group.units and group.units[1]
  return hasPrefix(unit and unit.name) or hasPrefix(group.name)
end

-- Drops every generated group, then hands out group and unit ids above what is left.
local function resetGenerated(mission)
  eachGroup(mission, function(groups, i, group)
    if isGenerated(group) then table.remove(groups, i) end
  end)
  local ids = { group = 0, unit = 0 }
  eachGroup(mission, function(_, _, group)
    if group.groupId and group.groupId > ids.group then ids.group = group.groupId end
    for _, unit in ipairs(group.units or {}) do
      if unit.unitId and unit.unitId > ids.unit then ids.unit = unit.unitId end
    end
  end)
  function ids.nextGroup() ids.group = ids.group + 1 return ids.group end
  function ids.nextUnit() ids.unit = ids.unit + 1 return ids.unit end
  return ids
end

-- The group list for `category` ("helicopter", "vehicle", "static") in the blue country.
local function blueGroups(mission, category)
  local blue = mission.coalition.blue
  blue.country = blue.country or {}
  ---@type table<string, any>?
  local country
  for _, c in ipairs(blue.country) do
    if c.id == BLUE_COUNTRY.id then country = c end
  end
  if not country then
    country = {}
    country.id, country.name = BLUE_COUNTRY.id, BLUE_COUNTRY.name
    table.insert(blue.country, country)
  end
  country[category] = country[category] or { group = {} }
  country[category].group = country[category].group or {}
  return country[category].group
end

---------------------------------------------------------------- player slots

local function addSlots(mission, ids, stands)
  local s = layout.slots
  local groups = blueGroups(mission, "helicopter")
  local number = 0

  local function slotGroup(heli, start, stand)
    local x, y = stand.x, stand.y
    number = number + 1
    local name = heli.displayName .. " " .. start.label
    local groupNumber = (number - 1) % 9 + 1
    return {
      name = name,
      groupId = ids.nextGroup(),
      x = x, y = y,
      task = "Nothing",
      tasks = {},
      start_time = 0,
      uncontrolled = false,
      hidden = false,
      communication = true,
      radioSet = false,
      frequency = heli.frequency,
      modulation = heli.modulation,
      route = {
        points = {
          {
            type = start.type, action = start.action,
            airdromeId = layout.airbaseId,
            x = x, y = y, alt = s.groundAlt, alt_type = "BARO",
            speed = 0, speed_locked = true, ETA = 0, ETA_locked = true,
            formation_template = "", name = "",
            task = { id = "ComboTask", params = { tasks = {} } },
          },
        },
      },
      units = {
        {
          name = M.SLOT_PREFIX .. name,
          unitId = ids.nextUnit(),
          type = heli.type,
          skill = "Client",
          x = x, y = y, alt = s.groundAlt, alt_type = "BARO",
          parking = stand.index, parking_id = stand.name,
          -- The game parks the aircraft by the stand's own heading; this copy of it is
          -- for scripts, such as the parked-helicopter copies.
          heading = math.rad(stand.heading),
          speed = 0,
          livery_id = heli.livery,
          onboard_num = string.format("%03d", number),
          callsign = { 1, groupNumber, 1, name = (heli.callsign or "Enfield") .. groupNumber .. "1" },
          payload = { fuel = heli.fuel, flare = heli.flare, chaff = heli.chaff, gun = heli.gun, pylons = {} },
          AddPropAircraft = heli.addProps,
          Radio = heli.radio,
        },
      },
    }
  end

  -- A helicopter's cold and hot slots sit side by side: the first two neighbouring free
  -- stands in one row that both fit it.
  local used = {}
  local function takePair(heli)
    for i = 1, #stands - 1 do
      local a, b = stands[i], stands[i + 1]
      if a.row == b.row and not used[a] and not used[b] and heli.size <= a.fits and heli.size <= b.fits then
        used[a], used[b] = true, true
        return a, b
      end
    end
    error("no two neighbouring free stands fit " .. heli.type .. " (" .. heli.size .. " m); add stands to layout.lua")
  end

  for _, heli in ipairs(helicopters) do
    local coldStand, hotStand = takePair(heli)
    table.insert(groups, slotGroup(heli, START.cold, coldStand))
    table.insert(groups, slotGroup(heli, START.hot, hotStand))
  end
  return number
end

---------------------------------------------------------------- dynamic spawn

-- Blue owns the airbase, multiplayer players can spawn any listed helicopter cold or
-- hot, and every other aircraft type is listed at zero so fixed wing stays unavailable
-- (an omitted type would come back at the editor's default amount on the next save).
local function configureAirbase(warehouses)
  local flyable = {}
  for _, heli in ipairs(helicopters) do
    if not aircraftTypes.helicopters[heli.type] then
      error("helicopters.lua lists " .. heli.type .. ", which aircraft_types.lua does not know")
    end
    flyable[heli.type] = true
  end

  local function entries(list, available)
    local t = {}
    for typeName, wsType in pairs(list) do
      local on = available[typeName] == true
      t[typeName] = { initialAmount = on and 1000000 or 0, unlimited = on, wsType = wsType }
    end
    return t
  end

  local airport = warehouses.airports[layout.airbaseId]
  airport.coalition = "BLUE"
  airport.dynamicSpawn = true
  airport.allowHotStart = true
  airport.unlimitedAircrafts = false
  airport.aircrafts = {
    planes = entries(aircraftTypes.planes, {}),
    helicopters = entries(aircraftTypes.helicopters, flyable),
  }
end

-- The Mission Editor opens its map here.
local function setEditorView(mission)
  local v = layout.view
  mission.map = { centerX = v.x, centerY = v.y, zoom = v.zoom }
end

---------------------------------------------------------------- mission scripts

-- In-mission scripts, bundled into one file in this order. Each file returns a module;
-- the bundle stores it as RotorGym.<name>.
M.SCRIPTS = { "parked" }
M.SCRIPT_FILE = "rotorgym.lua"
M.SCRIPT_TRIGGER = "Rotor Gym: load scripts"

function M.bundle(root)
  local out = { "-- Rotor Gym mission scripts. Generated by the build from scripts/; do not edit.",
                "RotorGym = RotorGym or {}" }
  for _, name in ipairs(M.SCRIPTS) do
    local f = assert(io.open(root .. "/scripts/" .. name .. ".lua", "rb"))
    local source = f:read("*a")
    f:close()
    out[#out + 1] = "RotorGym." .. name .. " = (function()\n" .. source .. "\nend)()"
  end
  out[#out + 1] = "RotorGym.parked.start()"
  return table.concat(out, "\n") .. "\n"
end

-- A mission-start trigger that runs the bundled script file. The editor compiles
-- trigrules into mission.trig when it saves, and the game runs mission.trig, so both
-- are written (me_trigrules.lua generateTrigger*). An earlier copy of the trigger is
-- reused, so rebuilding never duplicates it.
local function addScriptTrigger(mission, mapResource)
  mission.trigrules = mission.trigrules or {}
  local index, key
  for i, rule in ipairs(mission.trigrules) do
    if rule.comment == M.SCRIPT_TRIGGER then
      index, key = i, rule.actions[1] and rule.actions[1].file
    end
  end
  if not key then
    mission.maxDictId = (mission.maxDictId or 0) + 1
    key = "ResKey_Action_" .. mission.maxDictId
  end
  index = index or #mission.trigrules + 1
  mission.trigrules[index] = {
    predicate = "triggerStart", comment = M.SCRIPT_TRIGGER, eventlist = "", rules = {},
    colorItem = "0x0080ffff",
    actions = { { predicate = "a_do_script_file", file = key } },
  }
  local t = mission.trig
  for _, part in ipairs({ "actions", "events", "custom", "func", "flag", "conditions", "customStartup", "funcStartup" }) do
    t[part] = t[part] or {}
  end
  t.actions[index] = 'a_do_script_file(getValueResourceByKey("' .. key .. '"));'
  t.conditions[index] = "return(true)"
  t.funcStartup[index] = "if mission.trig.conditions[" .. index .. "]() then mission.trig.actions[" .. index .. "]() end"
  t.func[index] = nil
  t.flag[index] = true
  mapResource[key] = M.SCRIPT_FILE
end

-- options.stands overrides layout.stands (tests use it); options.mapResource is the
-- .miz's l10n/DEFAULT/mapResource table (a new one if omitted). The returned
-- mapResource must be written back.
function M.apply(mission, warehouses, options)
  options = options or {}
  local mapResource = options.mapResource or {}
  local ids = resetGenerated(mission)
  local slots = addSlots(mission, ids, options.stands or layout.stands)
  configureAirbase(warehouses)
  setEditorView(mission)
  addScriptTrigger(mission, mapResource)
  return { slots = slots, airbaseId = layout.airbaseId, mapResource = mapResource }
end

return M
